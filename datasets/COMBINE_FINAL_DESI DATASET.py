#!/usr/bin/env python3
"""
MERGES ALL TEMPORARY FILES (temp_lrg_*.fits) GENERATED BY THE SEQUENTIAL PROCESSING
AND SAVES THE FINAL CLEAN DATASET.

*** CORRECTED VERSION - NO nbytes ERROR ***
"""

import os
import glob
import numpy as np
from astropy.io import fits
from astropy.table import Table, vstack

OUTPUT_FINAL_FILENAME = "DATASET_LRG_VDISP_FLUXR_FINAL.fits"
TEMP_FILE_PATTERN = "temp_lrg_*.fits"

def calculate_memory_size(table):
    """Calculates the approximate in-memory size of a table"""
    total_size = 0
    for colname in table.colnames:
        col = table[colname]
        if hasattr(col, 'nbytes'):
            total_size += col.nbytes
        else:
            # Conservative estimate for columns without nbytes
            total_size += len(col) * 8  # Assumes 8 bytes per element
    return total_size

def verify_final_dataset(final_file):
    """Verifies that the final dataset is correct before deleting temporary files"""
    print(f"\n🔍 VERIFYING FINAL DATASET: {final_file}")
    print("-" * 50)

    try:
        with fits.open(final_file) as hdul:
            data = hdul[1].data  # HDU 1 is the data table
            n_objects = len(data)

            print(f"✅ FILE LOADED CORRECTLY")
            print(f"   • Number of objects: {n_objects:,}")
            print(f"   • Available columns: {len(data.names)}")

            # Check essential columns
            expected_columns = ['TARGETID', 'RA', 'DEC', 'Z', 'VDISP', 'VDISP_ERR', 'VDISP_IVAR', 'FLUX_R', 'DESI_TARGET']
            missing_columns = [col for col in expected_columns if col not in data.names]

            if missing_columns:
                print(f"❌ MISSING COLUMNS: {missing_columns}")
                return False
            else:
                print(f"✅ ALL ESSENTIAL COLUMNS PRESENT")

            # Basic quality statistics
            print(f"\n📊 QUALITY STATISTICS:")

            # VDISP
            vdisp_vals = data['VDISP']
            valid_vdisp = vdisp_vals[~np.isnan(vdisp_vals) & (vdisp_vals > 0)]
            print(f"   • Valid VDISP: {len(valid_vdisp):,}/{n_objects:,}")
            if len(valid_vdisp) > 0:
                print(f"   • VDISP range: {np.min(valid_vdisp):.1f} - {np.max(valid_vdisp):.1f} km/s")
                print(f"   • VDISP mean: {np.mean(valid_vdisp):.1f} ± {np.std(valid_vdisp):.1f} km/s")

            # Redshift
            z_vals = data['Z']
            valid_z = z_vals[~np.isnan(z_vals) & (z_vals > 0)]
            print(f"   • Valid Z: {len(valid_z):,}/{n_objects:,}")
            if len(valid_z) > 0:
                print(f"   • Z range: {np.min(valid_z):.3f} - {np.max(valid_z):.3f}")
                print(f"   • Z mean: {np.mean(valid_z):.3f} ± {np.std(valid_z):.3f}")

            # FLUX_R
            flux_vals = data['FLUX_R']
            valid_flux = flux_vals[~np.isnan(flux_vals) & (flux_vals > 0)]
            print(f"   • Valid FLUX_R: {len(valid_flux):,}/{n_objects:,}")
            if len(valid_flux) > 0:
                print(f"   • FLUX_R range: {np.min(valid_flux):.2f} - {np.max(valid_flux):.2f}")
                print(f"   • FLUX_R median: {np.median(valid_flux):.2f}")

            # Check for TARGETID duplicates
            targetids = data['TARGETID']
            duplicates = len(targetids) - len(np.unique(targetids))
            print(f"   • TARGETID duplicates: {duplicates}")

            # Distribution between dark/bright
            desi_target = data['DESI_TARGET']
            lrg_mask = 2 ** 0  # LRG bit
            lrg_count = np.sum((desi_target & lrg_mask) != 0)
            print(f"   • LRG confirmation: {lrg_count:,}/{n_objects:,}")

            return True

    except Exception as e:
        print(f"❌ ERROR in verification: {e}")
        return False

def inspect_temporaries():
    """Inspects temporary files before combining them"""
    temporary_files = sorted(glob.glob(TEMP_FILE_PATTERN))

    if not temporary_files:
        print("❌ No temporary files found")
        return []

    print(f"📋 TEMPORARY FILES FOUND ({len(temporary_files)}):")
    total_objects = 0

    for file_name in temporary_files:
        try:
            with fits.open(file_name) as hdul:
                n_obj = len(hdul[1].data)
                total_objects += n_obj
                print(f"   • {os.path.basename(file_name)}: {n_obj:,} objects")
        except:
            print(f"   • {os.path.basename(file_name)}: ERROR reading")

    print(f"📊 ESTIMATED TOTAL: {total_objects:,} objects")
    return temporary_files

def combine_datasets():
    print("🚀 INITIATING TEMPORARY FILE COMBINATION")
    print("=" * 70)

    # 1. Inspect temporary files
    temporary_files = inspect_temporaries()

    if not temporary_files:
        return

    # 2. Confirm with user before proceeding
    print(f"\n⚠️  Continue with combination? (y/n): ", end="")
    respuesta = input().strip().lower()

    if respuesta not in ['s', 'si', 'y', 'yes']:
        print("❌ Combination canceled by user")
        return

    # 3. Read and combine tables
    print("\n💾 LOADING AND COMBINING TABLES...")
    list_of_tables = []

    for i, file_name in enumerate(temporary_files):
        try:
            table = Table.read(file_name)
            list_of_tables.append(table)
            print(f"   ✅ [{i+1:2d}/{len(temporary_files)}] {os.path.basename(file_name)}: {len(table):,} objects")
        except Exception as e:
            print(f"   ❌ [{i+1:2d}/{len(temporary_files)}] {os.path.basename(file_name)}: ERROR - {e}")

    if not list_of_tables:
        print("❌ Could not load any tables")
        return

    # 4. Join tables
    print("\n✨ STACKING TABLES (vstack)...")
    try:
        final_dataset = vstack(list_of_tables)
        print(f"✅ STACKING SUCCESSFUL")
        print(f"   • Total combined objects: {len(final_dataset):,}")
        print(f"   • Final columns: {len(final_dataset.colnames)}")

        # Calculate memory size (CORRECTED)
        size_mb = calculate_memory_size(final_dataset) / 1024 / 1024
        print(f"   • Memory: {size_mb:.1f} MB")

    except Exception as e:
        print(f"❌ ERROR in vstack: {e}")
        return

    # 5. Save final dataset
    print(f"\n💾 SAVING FINAL DATASET...")
    try:
        final_dataset.write(OUTPUT_FINAL_FILENAME, overwrite=True)
        print(f"✅ DATASET SAVED: {OUTPUT_FINAL_FILENAME}")
    except Exception as e:
        print(f"❌ ERROR saving: {e}")
        return

    # 6. CRITICAL VERIFICATION BEFORE CLEANING
    print(f"\n🔍 PERFORMING FINAL VERIFICATION...")
    if verify_final_dataset(OUTPUT_FINAL_FILENAME):
        print(f"\n🎉 VERIFICATION SUCCESSFUL! FINAL DATASET READY")

        # 7. ONLY NOW ask about cleanup
        print(f"\n⚠️  Delete temporary files? (y/n): ", end="")
        cleanup_response = input().strip().lower()

        if cleanup_response in ['s', 'si', 'y', 'yes']:
            print("🧹 DELETING TEMPORARY FILES...")
            deleted_count = 0
            for file_name in temporary_files:
                try:
                    os.remove(file_name)
                    deleted_count += 1
                    print(f"   ✅ Deleted: {os.path.basename(file_name)}")
                except Exception as e:
                    print(f"   ⚠️  Could not delete {file_name}: {e}")
            print(f"📊 {deleted_count}/{len(temporary_files)} temporary files deleted")
        else:
            print("ℹ️  Temporary files kept")
    else:
        print(f"\n❌ VERIFICATION FAILED - Temporary files WILL NOT be deleted")
        print("💡 Manually check the final dataset before proceeding")

    print("\n" + "=" * 70)
    print("🎉 COMBINATION PROCESS COMPLETED")
    print(f"📁 Final dataset: {OUTPUT_FINAL_FILENAME}")
    print(f"📊 Total LRG with VDISP: {len(final_dataset):,}")
    print("=" * 70)

if __name__ == "__main__":
    combine_datasets()